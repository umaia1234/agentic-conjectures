#!/usr/bin/env bash
# Reproduce the exhaustive WOWII conjecture 61 computations (local only:
# needs nauty's geng/gentreeg, g++ and python3).
#
#   bash run_exhaustive.sh OUTDIR STAGE [JOBS]
#
# STAGE is one of
#   conn     connected graphs n = 1..10 (geng -c), brute-force crosscheck on,
#            hash sample of n = 10 dumped (--dump-mod 64)
#   conn11   connected graphs n = 11 in 256 geng res/mod parts, hash sample
#            dumped (--dump-mod 4096)
#   trees    all trees n = 1..26 (gentreeg), n >= 22 split in 64 parts
#   sparse   connected graphs with cyclomatic number m-n+1 <= c (geng -c n
#            n-1:n-1+c) for (n, c) in SPARSE below
#   ref      independent Python reference: all connected graphs n <= 9
#            (summary diff against the C++ result) and the dumped samples of
#            n = 10, 11 (--check-dump, networkx cross-check if available),
#            plus the C++ brute-force crosscheck of the n = 11 sample
#   diampath connected graphs with diameter D >= n-5 (diampath_gen | shortg),
#            validated against the geng counts for n <= 11 (needs conn and
#            conn11 first), then n = 12..18
# JOBS (default 3) is the number of parallel geng|wowii61 pipelines.
# Merged summaries are written to OUTDIR (connected_n1-10.txt,
# connected_n11.txt, trees_n1-26.txt, sparse.txt, diampath_n12-18.txt); they
# should be identical to the committed files in results/.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
out=${1:?usage: run_exhaustive.sh OUTDIR STAGE [JOBS]}
stage=${2:?stage}
jobs=${3:-3}
py=${PYTHON:-python3}
mkdir -p "$out"
bin="$out/wowii61"
[ -x "$bin" ] || g++ -O3 -std=c++17 "$here/wowii61.cpp" -o "$bin"
merge() { "$py" "$here/wowii61_summary.py" merge "$@"; }
# par CMD: run CMD (a bash snippet using $1) once per input line, JOBS at a time
par() { xargs -n 1 -P "$jobs" bash -c "set -euo pipefail; $1" _; }
export here bin py d
SPARSE="12:4 13:4 14:4 15:4 16:3 17:3 18:2 19:2 20:2"

case "$stage" in
conn)
  d="$out/conn"; mkdir -p "$d"
  for n in 1 2 3 4 5 6 7 8 9; do
    geng -cq "$n" | "$bin" --crosscheck > "$d/n$n.txt"
  done
  seq 0 63 | par 'geng -cq 10 "$1/64" | "$bin" --crosscheck --dump "$d/dump10_$1.txt" \
    --dump-mod 64 > "$d/n10_$1.txt"'
  merge "$d"/n*.txt > "$out/connected_n1-10.txt"
  cat "$d"/dump10_*.txt > "$out/sample10.txt"
  ;;
conn11)
  d="$out/conn11"; mkdir -p "$d"
  seq 0 255 | par '[ -s "$d/part_$1.txt" ] || { geng -cq 11 "$1/256" |
    "$bin" --dump "$d/dump_$1.tmp" --dump-mod 4096 > "$d/part_$1.tmp" &&
    mv "$d/dump_$1.tmp" "$d/dump_$1.txt" && mv "$d/part_$1.tmp" "$d/part_$1.txt"; }'
  merge "$d"/part_*.txt > "$out/connected_n11.txt"
  cat "$d"/dump_*.txt > "$out/sample11.txt"
  ;;
trees)
  d="$out/trees"; mkdir -p "$d"
  for n in $(seq 1 21); do
    gentreeg -pq "$n" | "$bin" --parent > "$d/n$n.txt"
  done
  for n in 22 23 24 25 26; do
    export n
    seq 0 63 | par 'gentreeg -pq "$n" "$1/64" | "$bin" --parent > "$d/n${n}_$1.txt"'
  done
  merge "$d"/n*.txt > "$out/trees_n1-26.txt"
  ;;
sparse)
  d="$out/sparse"; mkdir -p "$d"
  for nc in $SPARSE; do
    n=${nc%:*}; c=${nc#*:}
    export n c
    seq 0 15 | par 'geng -cq "$n" "$((n - 1)):$((n - 1 + c))" "$1/16" | "$bin" \
      > "$d/n${n}_c${c}_$1.txt"'
    merge "$d"/n${n}_c${c}_*.txt > "$d/n${n}_c${c}.txt"
  done
  merge $(for nc in $SPARSE; do echo "$d/n${nc%:*}_c${nc#*:}.txt"; done) > "$out/sparse.txt"
  ;;
ref)
  d="$out/ref"; mkdir -p "$d"
  nxflag=""
  "$py" -c "import networkx" 2>/dev/null && nxflag="--nx"
  for n in 1 2 3 4 5 6 7 8; do
    geng -cq "$n" | "$py" "$here/wowii61_ref.py" $nxflag > "$d/py_n$n.txt"
  done
  export nxflag
  seq 0 15 | par 'geng -cq 9 "$1/16" | "$py" "$here/wowii61_ref.py" $nxflag \
    > "$d/py_n9_$1.txt"'
  merge "$d"/py_n*.txt > "$d/py_conn9.txt"
  merge "$out"/conn/n[1-9].txt > "$d/cpp_conn9.txt"
  diff <(grep -v CROSSCHECK "$d/py_conn9.txt") <(grep -v CROSSCHECK "$d/cpp_conn9.txt") ||
    { echo "n <= 9: Python and C++ summaries differ" >&2; exit 1; }
  echo "n <= 9: Python reference summary identical to C++ summary"
  for s in sample10 sample11; do
    awk -v J="$jobs" -v p="$d/${s}_chunk_" '{ print > (p (NR % J)) }' "$out/$s.txt"
    ls "$d/${s}_chunk_"[0-9]* | grep -v '\.log$' |
      par '"$py" "$here/wowii61_ref.py" --check-dump "$1" $nxflag | tail -1 > "$1.log"'
    cat "$d/${s}_chunk_"*.log
  done
  cut -d' ' -f1 "$out/sample11.txt" | "$bin" --crosscheck > "$d/sample11_crosscheck.txt"
  grep -E "^CHECK 11 x" "$d/sample11_crosscheck.txt"
  awk '$1 == "CHECK" && $4 != 0 { bad = 1 } END { exit bad }' "$d/sample11_crosscheck.txt"
  ;;
diampath)
  # connected graphs with diameter D >= n-5 (at most 4 vertices off a
  # diametral path), generated by diampath_gen and deduplicated by shortg;
  # validated against the geng counts for n <= 11
  d="$out/diampath"; mkdir -p "$d"
  gen="$out/diampath_gen"
  [ -x "$gen" ] || g++ -O3 -std=c++17 "$here/diampath_gen.cpp" -o "$gen"
  export gen
  "$py" "$here/wowii61_summary.py" ndcount "$out/connected_n1-10.txt" \
    "$out/connected_n11.txt" > "$d/geng_nd.txt"
  for n in $(seq 2 11); do
    for D in $(seq $((n > 6 ? n - 5 : 1)) $((n - 1))); do
      got=$("$gen" "$n" "$D" 2>/dev/null | shortg -q | wc -l | tr -d ' ')
      want=$(awk -v n="$n" -v D="$D" '$1 == n && $2 == D { print $3 }' "$d/geng_nd.txt")
      echo "validate n=$n D=$D: diampath_gen classes $got, geng ${want:-0}"
      [ "$got" = "${want:-0}" ] || { echo "MISMATCH" >&2; exit 1; }
    done
  done
  for n in $(seq 12 18); do
    for D in $(seq $((n - 5)) $((n - 1))); do echo "${n}_$D"; done
  done | par 'n=${1%_*}; D=${1#*_}; "$gen" "$n" "$D" 2>/dev/null | shortg -q |
    "$bin" > "$d/n${n}_D$D.txt"'
  merge "$d"/n*_D*.txt > "$out/diampath_n12-18.txt"
  ;;
*)
  echo "unknown stage $stage" >&2; exit 2 ;;
esac
