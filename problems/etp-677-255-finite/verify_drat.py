#!/usr/bin/env python3
"""Check the DRAT certificates for sizes n = 1..8 (and optionally regenerate
and check the ones for larger n).

For each n the CNF (no magma on {0..n-1} satisfies E677, is generated by 0 in
canonical labelling and fails E255 at 0) is regenerated with
search/gen_cnf.py and its SHA-256 is compared with certificates/SHA256SUMS;
then drat-trim must report "s VERIFIED" for certificates/a<n>.drat.

  python3 verify_drat.py                 # n = 1..8, committed proofs (CI)
  python3 verify_drat.py --solve 9 10    # re-solve with cadical, then drat-trim
The second form writes the proofs to a temporary directory (n = 10 needs
about 0.7 GB of disk and some 15 minutes)."""
import argparse
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
CERT = HERE / "certificates"


def expected_hashes():
    sums = {}
    for line in open(CERT / "SHA256SUMS"):
        h, name = line.split()
        sums[name] = h
    return sums


def drat_check(cnf, proof):
    out = subprocess.run(["drat-trim", str(cnf), str(proof)], capture_output=True, text=True).stdout
    lines = [l.strip() for l in out.replace("\r", "\n").splitlines()]
    return "s VERIFIED" in lines, [l for l in lines if l.startswith("c verification time")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--solve", type=int, nargs="*", metavar="N")
    args = ap.parse_args()
    sums = expected_hashes()
    sizes = args.solve if args.solve else range(1, 9)
    ok = True
    with tempfile.TemporaryDirectory() as tmp:
        for n in sizes:
            cnf_text = subprocess.run([sys.executable, str(HERE / "search" / "gen_cnf.py"), str(n)],
                                      check=True, capture_output=True, text=True).stdout
            h = hashlib.sha256(cnf_text.encode()).hexdigest()
            if h != sums.get("a%d.cnf" % n):
                print("FAIL n=%d: CNF hash %s differs from SHA256SUMS" % (n, h))
                ok = False
                continue
            cnf = Path(tmp) / ("a%d.cnf" % n)
            cnf.write_text(cnf_text)
            if args.solve:
                proof = Path(tmp) / ("a%d.drat" % n)
                r = subprocess.run(["cadical", "-q", str(cnf), str(proof)], capture_output=True, text=True)
                if r.returncode != 20:
                    print("FAIL n=%d: cadical exit code %d (expected 20 = UNSAT)" % (n, r.returncode))
                    ok = False
                    continue
            else:
                proof = CERT / ("a%d.drat" % n)
                if hashlib.sha256(proof.read_bytes()).hexdigest() != sums["a%d.drat" % n]:
                    print("FAIL n=%d: proof hash differs from SHA256SUMS" % n)
                    ok = False
                    continue
            verified, info = drat_check(cnf, proof)
            print("%s n=%d %s" % ("VERIFIED" if verified else "FAIL", n, " ".join(info)))
            ok &= verified
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
