#!/usr/bin/env python3
"""Re-run the exhaustive DFS (search/dfs677.cpp) for sizes n <= 9.

* anti-E255 mode: for every n = 1..9 there is no magma on {0..n-1} that
  satisfies E677, is generated by 0 and fails E255 at 0;
* general mode: the canonical tables of all pointed E677 magmas generated
  by 0 are exactly those in results/general_tables.txt (1,0,0,0,0,0,2,0,1
  tables for n = 1..9).

Every listed table is re-checked here in Python, independently of the C++
code: E677 holds, the labelling is the canonical row-major generation
labelling (so the table is generated by 0), and E255 holds at 0, consistent
with the empty anti-E255 searches.  The C++ program is compiled from source
into a temporary directory."""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
NMAX = 9


def canonical(T, n):
    for k in range(n - 1):
        first = next(((i, j) for i in range(k + 1) for j in range(k + 1) if T[i][j] > k), None)
        if first is None or T[first[0]][first[1]] != k + 1:
            return False
    return True


def e677(T, n):
    return all(T[y][T[x][T[T[y][x]][y]]] == x for x in range(n) for y in range(n))


def run(exe, *args):
    out = subprocess.run([str(exe), *map(str, args)], check=True, capture_output=True,
                         text=True, timeout=170).stdout
    res = [l for l in out.splitlines() if l.startswith("RESULT")]
    assert len(res) == 1, out
    sols = int(re.search(r"solutions=(\d+)", res[0]).group(1))
    tables = [tuple(map(int, l.split()[1:])) for l in out.splitlines() if l.startswith("SOL")]
    return sols, tables, res[0]


def main():
    expected = {n: [] for n in range(1, NMAX + 1)}
    for line in open(HERE / "results" / "general_tables.txt"):
        if line.startswith("n="):
            head, _, rest = line.partition(" SOL ")
            n = int(head[2:])
            tab = tuple(map(int, rest.split()))
            assert len(tab) == n * n
            T = [tab[i * n:(i + 1) * n] for i in range(n)]
            assert e677(T, n) and canonical(T, n), line
            assert T[T[T[0][0]][0]][0] == 0, line       # E255 holds at 0
            expected[n].append(tab)
    with tempfile.TemporaryDirectory() as tmp:
        exe = Path(tmp) / "dfs677"
        subprocess.run(["g++", "-O2", "-std=c++17", str(HERE / "search" / "dfs677.cpp"), "-o", str(exe)],
                       check=True, capture_output=True, text=True, timeout=120)
        for n in range(1, NMAX + 1):
            sols, _, res = run(exe, n, "sel", 2)
            print(res)
            assert sols == 0, "anti-E255 solution found at n=%d" % n
            sols, tables, res = run(exe, n, "general", "print", "sel", 2)
            print(res)
            assert sols == len(tables) and sorted(tables) == sorted(expected[n]), "general mismatch at n=%d" % n
    print("OK: no anti-E255 E677 magma generated by 0 for n <= %d; general tables match" % NMAX)


if __name__ == "__main__":
    sys.exit(main())
